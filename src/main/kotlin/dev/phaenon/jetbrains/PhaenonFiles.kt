package dev.phaenon.jetbrains

import com.intellij.openapi.vfs.VirtualFile
import com.intellij.psi.PsiFile

/**
 * The one fact every part of the plugin shares: which files are Phaenon source.
 *
 * Kept free of PHP plugin imports on purpose. The pieces that run without the PHP plugin (file
 * icon, TextMate fallback) load this class, and a reference to a PHP class from here would make
 * them fail to load in IDEs where PHP support is absent or disabled.
 */
object PhaenonFiles {

    const val EXTENSION: String = "phn"

    const val PLUGIN_ID: String = "dev.phaenon.jetbrains"

    /** The project file `phn build` and `phn check` read: the source roots and their output directories. */
    const val PROJECT_FILE: String = "phaenon.json"

    /** What the first line of every file `phn build` writes carries: `<?php /* @generated by phaenon … */`. */
    const val GENERATED_MARKER: String = "@generated by phaenon"

    @JvmStatic
    fun isPhaenonFile(file: VirtualFile?): Boolean =
        file != null && EXTENSION.equals(file.extension, ignoreCase = true)

    /**
     * Whether the file is the `.php` the compiler wrote from a `.phn`: a PHP file whose first line
     * carries the marker. Such a file declares what its source declares; the source is where
     * people and the IDE should land.
     */
    @JvmStatic
    fun isGeneratedOutput(file: PsiFile?): Boolean {
        val virtual = file?.viewProvider?.virtualFile ?: return false
        if (!"php".equals(virtual.extension, ignoreCase = true)) return false
        val text = file.viewProvider.contents
        val end = text.indexOf('\n').let { if (it < 0) text.length else it }
        return text.subSequence(0, end).contains(GENERATED_MARKER)
    }
}
